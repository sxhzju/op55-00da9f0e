// Pull stroke-order medians for every Han character in subtitles.srt (plus a few
// extras used in the artwork) out of hanzi-writer-data into src/glyphs.js.
// Data: Make Me a Hanzi / Hanzi Writer, derived from Arphic PL fonts (see LICENSES/).
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const srt = fs.readFileSync(path.join(root, 'subtitles.srt'), 'utf8');
const text = srt.split(/\r?\n/).filter((l) => l && !/^\d+$/.test(l) && !l.includes('-->')).join('');
const chars = [...new Set([...text].filter((c) => /\p{Script=Han}/u.test(c)))];

const out = {};
for (const c of chars) {
  const d = require(`hanzi-writer-data/${c}.json`);
  // Medians live in a 1024 box with y up and the top at y=900. Store them in a
  // unit box with y down so the renderer can treat every glyph the same way.
  out[c] = d.medians.map((m) => m.map(([x, y]) => [+(x / 1024).toFixed(4), +((900 - y) / 1024).toFixed(4)]));
}
const body = `// Generated by scripts/extract-glyphs.mjs - do not edit.\n// Stroke medians from hanzi-writer-data (Arphic Public License, see LICENSES/ARPHICPL.TXT).\nexport default ${JSON.stringify(out)};\n`;
fs.writeFileSync(path.join(root, 'src/glyphs.js'), body);
console.log(`${chars.length} glyphs: ${chars.join('')}`);
